// Pure rules behind the .claude/hooks guards. No I/O here, so every rule is unit-tested
// (tools/__tests__/hook-rules.test.mjs). Each finding: { rule, decision?, message }.
//
// The rules protect the four graded invariants (CLAUDE.md "What is actually being graded"):
// no oversubscription, idempotency, reconciliation ordering, the currency invariant. Plus the
// ledger decision and "every endpoint authenticated".

// Files that define, test or document the rules, so they must be able to name what they forbid.
export const isRuleSource = (rel) =>
  /^(tools\/|\.claude\/|docs\/|CLAUDE\.md$|AGENTS\.md$|README\.md$)/.test(rel);

const isAppSource = (rel) => /^src\/.+\.ts$/.test(rel) && !/\.spec\.ts$/.test(rel);
const isMigration = (rel) => /^migrations\/.+\.(sql|ts)$/.test(rel);

// ---------- Protected and generated files ----------

const PROTECTED = [
  [/^pnpm-lock\.yaml$/, 'generated by pnpm; change dependencies with `pnpm add`, never by hand'],
  [/(^|\/)\.env(\.[^/]*)?$/, 'a secrets file; never written by Claude (put names only in .env.example)'],
  [/(^|\/)(dist|coverage|node_modules)\//, 'build output; edit the source instead'],
  [/^\.husky\/_\//, 'generated by husky'],
  [
    /^docs\/api\/openapi\.json$/,
    'generated from the @nestjs/swagger decorators; change them and run `pnpm run docs:export` (api-docs skill)',
  ],
];

export function protectedFileFindings(rel) {
  if (/(^|\/)\.env\.example$/.test(rel)) {
    return [];
  }
  return PROTECTED.filter(([re]) => re.test(rel)).map(([, why]) => ({
    rule: 'protected-file',
    message: `\`${rel}\` is ${why}.`,
  }));
}

// ---------- Committed migrations are immutable ----------

// ctx.committed: the file exists in HEAD (the hook asks git). A migration that may have run
// anywhere is history; a fix is a new migration.
export function migrationFindings(rel, ctx = {}) {
  if (!isMigration(rel) || !ctx.committed) {
    return [];
  }
  return [
    {
      rule: 'migration-immutable',
      message: `\`${rel}\` is committed, so it may already have run. Add a new migration instead of editing it (ledger-model skill).`,
    },
  ];
}

// ---------- Hard rules on the content of an edit (pre-edit: deny) ----------

export function hardRuleFindings(rel, content = '') {
  if (isRuleSource(rel)) {
    return [];
  }
  const f = [];
  if ((isAppSource(rel) || isMigration(rel)) && /\bsynchronize\s*:\s*true\b/.test(content)) {
    f.push({
      rule: 'no-synchronize',
      message: 'Schema changes go through migration files, never `synchronize: true` (ledger-model skill).',
    });
  }
  // The ledger is append-only. A trigger that *forbids* UPDATE/DELETE reads "BEFORE UPDATE OR DELETE ON
  // ledger_entries" and does not match these statements.
  if (
    (isAppSource(rel) || isMigration(rel)) &&
    /\b(update\s+ledger_entries\b|delete\s+from\s+ledger_entries\b|truncate\s+(table\s+)?ledger_entries\b)/i.test(
      content
    )
  ) {
    f.push({
      rule: 'ledger-append-only',
      message:
        'ledger_entries is append-only: corrections are new compensating rows, never UPDATE/DELETE (ledger-model skill). Tests reset with TRUNCATE in test/ helpers only.',
    });
  }
  if (isAppSource(rel) && /@(Public|SkipAuth|AllowAnonymous)\s*\(/.test(content)) {
    f.push({
      rule: 'auth-everywhere',
      message:
        'Every endpoint is authenticated, availability reads included. No public-route decorators; tokens come from `pnpm run token` (nestjs-service skill).',
    });
  }
  return f;
}

// ---------- Money: integer minor units only (post-edit: block, new occurrences only) ----------

const MONEY_NAME = String.raw`\w*(amount|minor|credit_?limit|reserved|available|balance|utili[sz]ed|capacity)\w*`;
const MONEY_AS_NUMBER = new RegExp(String.raw`\b${MONEY_NAME}\??\s*:\s*number\b`, 'gi');
const FLOAT_OPS = /\bparseFloat\s*\(|\.toFixed\s*\(|\bMath\.(round|floor|ceil)\s*\(/g;
const FLOAT_COLUMNS = /\b(real|double\s+precision|float[48]?|money)\b/gi;

const added = (re, before, after) => {
  const had = new Set((before.match(re) ?? []).map((s) => s.toLowerCase()));
  const seen = new Set();
  return (after.match(re) ?? []).filter((s) => {
    const k = s.toLowerCase();
    return !had.has(k) && !seen.has(k) && seen.add(k);
  });
};

export function moneyFindings(rel, before = '', after = '') {
  const f = [];
  if (isAppSource(rel)) {
    const typed = added(MONEY_AS_NUMBER, before, after);
    if (typed.length) {
      f.push({
        rule: 'money-bigint',
        message: `money typed as \`number\`: ${typed.join(', ')}. Amounts are integer minor units as \`bigint\` in code and decimal strings on the wire (money-and-fx skill).`,
      });
    }
    const ops = added(FLOAT_OPS, before, after);
    if (ops.length) {
      f.push({
        rule: 'money-float',
        message: `float arithmetic (${ops.join(', ')}) in app code. Use the bigint helpers in src/money/ with an explicit rounding mode; if this is not money, name it so (money-and-fx skill).`,
      });
    }
  }
  if (isMigration(rel)) {
    // SQL comments may say "money" in prose; only code counts.
    const code = (sql) => sql.replace(/--[^\n]*/g, '').replace(/\/\*[\s\S]*?\*\//g, '');
    const cols = added(FLOAT_COLUMNS, code(before), code(after));
    if (cols.length) {
      f.push({
        rule: 'money-column',
        message: `column type ${cols.join(', ')} in a migration. Money is BIGINT minor units; an FX rate is NUMERIC (ledger-model skill).`,
      });
    }
  }
  return f;
}

// ---------- Content after an Edit / Write / MultiEdit ----------

export function contentAfter(toolName, input, before) {
  if (toolName === 'Write') {
    return input.content ?? '';
  }
  const edits = toolName === 'MultiEdit' ? (input.edits ?? []) : [input];
  let text = before;
  for (const e of edits) {
    if (e.old_string === undefined) {
      continue;
    }
    text = e.replace_all
      ? text.split(e.old_string).join(e.new_string ?? '')
      : text.replace(e.old_string, () => e.new_string ?? '');
  }
  return text;
}

// ---------- Bash policy for every session ----------

export function bashFindings(command, ctx = {}) {
  const f = [];
  const deny = (rule, message) => f.push({ rule, decision: 'deny', message });
  const ask = (rule, message) => f.push({ rule, decision: 'ask', message });

  if (/(^|[;&|]\s*)(npm\s+(i|install|add|ci)\b|yarn(\s+add)?\b|bun\s+(add|install)\b)/.test(command)) {
    deny(
      'pnpm-only',
      'This repo uses pnpm: `pnpm add <pkg>` (ask first unless it is Nest, Postgres, Kafka or test tooling).'
    );
  }
  if (/(^|[;&|]\s*)npx\s/.test(command)) {
    deny('pnpm-only', 'Use `pnpm exec <bin>` for local binaries or `pnpm dlx <pkg>` for one-off packages.');
  }
  if (/\bgit\b[^;&|]*--no-verify\b|\bgit\s+commit\b[^;&|]*\s-n\b/.test(command)) {
    deny('no-verify', 'Never skip git hooks; fix what the hook reports.');
  }
  if (/\bgit\s+push\b[^;&|]*(\s--force\b|\s-f\b|\s\+\S)/.test(command)) {
    deny('force-push', 'No force-push. Add a new commit instead (ask the user if history must change).');
  }
  if (
    /\bgit\s+push\b[^;&|]*\b(origin\s+)?(HEAD:)?main\b/.test(command) ||
    (/\bgit\s+push\b/.test(command) && ctx.branch === 'main')
  ) {
    deny(
      'push-main',
      'Never push to main. Branch (`git switch -c feat/<area>`) and open a PR (ship-branch skill).'
    );
  }
  if (/\bgh\s+pr\s+merge\b/.test(command)) {
    ask('merge', 'Merging is the user’s call. Confirm before merging this PR.');
  }
  if (/\bgh\s+repo\s+create\b[^;&|]*--public\b/.test(command)) {
    ask('public-repo', 'A public repository publishes the take-home. Confirm visibility with the user.');
  }
  if (
    /\bdocker\s+compose\b[^;&|]*\bdown\b[^;&|]*(\s-v\b|\s--volumes\b)|\bdocker\s+volume\s+(rm|prune)\b/.test(
      command
    )
  ) {
    ask(
      'wipe-volumes',
      'This deletes the local Postgres and Redpanda data. Confirm, or use `docker compose down` without -v.'
    );
  }
  return f;
}

// ---------- Read-only Bash for reviewer / planner agents ----------

const WRITE_CMDS =
  /(^|[;&|(]\s*|\bxargs\s+)(rm|mv|cp|mkdir|rmdir|touch|chmod|chown|ln|tee|truncate|dd|install|patch)\b/;
const GIT_WRITE =
  /\bgit\s+(add|commit|push|checkout|switch|reset|restore|merge|rebase|stash|tag|clean|rm|mv|cherry-pick|revert|am|apply|worktree|init)\b/;
const PKG_WRITE =
  /\bpnpm\s+(add|remove|rm|install|i|up|update|dlx|create|init|link|unlink)\b|\bnpx\b|\bnpm\b|\byarn\b/;
const CODE_EXEC =
  /\b(node|python3?|ruby|perl|deno|bun)\s+(-e|-c|--eval|-p)\b|\bsed\s+[^|;&]*-i\b|\bperl\s+-[^ ]*i/;
// Reviewers may read the database, never change it or the stack.
const DB_WRITE =
  /\b(insert\s+into|update\s+\w+\s+set|delete\s+from|truncate|drop\s+|alter\s+table|create\s+table)\b/i;
const STACK_WRITE = /\bdocker\s+(compose\s+)?(down|rm|kill|stop|volume|system\s+prune)\b/;

export function readOnlyBashFindings(command, scope = {}) {
  const f = [];
  const writable = scope.writable ?? null;
  const deny = (rule, message) => f.push({ rule, message });

  for (const m of command.matchAll(/(?<![0-9&<])>{1,2}\s*([^\s;&|)]+)/g)) {
    const target = m[1];
    const okTemp = /^(\/dev\/null|\/tmp\/|\/private\/tmp\/|\$TMPDIR|"\$TMPDIR)/.test(target);
    const okScoped = writable?.some((p) => target.replace(/^\.\//, '').startsWith(p));
    if (!okTemp && !okScoped) {
      deny('read-only', `redirect into \`${target}\` writes a file; this agent is read-only there.`);
    }
  }
  if (WRITE_CMDS.test(command)) {
    deny('read-only', 'file-changing command; this agent may not modify the working tree from Bash.');
  }
  if (PKG_WRITE.test(command)) {
    deny(
      'read-only',
      'package installs and one-off packages are off-limits; use `pnpm run <script>` or `pnpm exec <bin>`.'
    );
  }
  if (CODE_EXEC.test(command)) {
    deny('read-only', 'inline code or in-place edits; use `jq`, `grep`, `sed -n` instead.');
  }
  if (/\bpsql\b/.test(command) && DB_WRITE.test(command)) {
    deny('read-only', 'database write from a read-only agent; SELECT only.');
  }
  if (STACK_WRITE.test(command)) {
    deny('read-only', 'stopping or removing containers or volumes; report it instead.');
  }
  const gitWrite = command.match(GIT_WRITE);
  if (gitWrite) {
    const shipping = /\bgit\s+(add|commit|push|switch|checkout)\b/.test(command);
    if (!(writable && shipping)) {
      deny('read-only', `\`git ${gitWrite[1]}\` changes repository state.`);
    }
  }
  if (
    /\bgh\s+(pr|issue|release|repo)\s+(create|edit|merge|close|delete|comment)\b/.test(command) &&
    !writable
  ) {
    deny('read-only', 'GitHub write; report what should be done instead.');
  }
  return f;
}

// ---------- Edit allow-lists for agents with owned paths ----------

export function editAllowed(rel, list) {
  return list.some((p) => (p.endsWith('/') ? rel.startsWith(p) : rel === p));
}

